export const DICTS: Record<Locale, Partial<Dict>> = {
  en,
  fr: { ...fr, ...frExtra } as Partial<Dict>,
  ar: { ...ar, ...arExtra } as Partial<Dict>
};

export function t(locale: Locale, key: string): string {
  const d = DICTS[locale];
  if (key in d) return d[key as keyof Dict] as string;
  const e = (en as Record<string, string>)[key];
  return e ?? key;
}

/** t() with {placeholder} interpolation. Placeholders stay translators' word order. */
export function tx(locale: Locale, key: string, vars: Record<string, string | number>): string {
  let s = t(locale, key);
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function isRTL(locale: Locale): boolean {
  return locale === "ar";
}
